def validate(payload: dict[str, Any]) -> None:
    theorem, rec, control, decision = payload["closure_theorem"], payload["K590_K607_reconciliation"], payload["exact_controls"], payload["decision"]
    assert theorem["spectral_block_ranks"] == [192, 192, 64, 64]
    assert theorem["minimum_nonzero_carrier_idempotent_rank"] == 64 and not theorem["rank_one_packet_in_factorwise_closure"]
    assert rec["full_available_factorwise_algebra_tested"] and not rec["K590_factorized_exact_complex_retracted"] and not rec["K607_action_symbol_result_retracted"]
    assert control["minimum_nonzero_carrier_rank"] == 64 and control["minimum_nonzero_factorwise_rank"] == 64 and control["rank_one_absent"]
    assert not decision["factorwise_algebra_selects_carrier_vector_or_covector"] and not decision["factorwise_algebra_selects_rank_one_packet"] and not decision["K598_released"]
    assert not decision["selected_source_action_rejected"] and decision["nonfactorized_action_data_remain_live"]


