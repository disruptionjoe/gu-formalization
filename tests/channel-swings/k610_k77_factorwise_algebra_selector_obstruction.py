def strict(path: str) -> dict[str, Any]:
    return json.loads((ROOT / path).read_text())


def exact_control(block_ranks: list[int]) -> dict[str, Any]:
    ranks = sorted({sum(rank for keep, rank in zip(mask, block_ranks) if keep) for mask in product((0, 1), repeat=len(block_ranks))})
    nonzero = [rank for rank in ranks if rank]
    base_ranks = [1, 2, 3]
    factorwise_ranks = sorted({base * carrier for base in base_ranks for carrier in nonzero})
    return {
        "spectral_subset_ranks": ranks,
        "minimum_nonzero_carrier_rank": min(nonzero),
        "toy_base_ranks": base_ranks,
        "toy_factorwise_nonzero_ranks": factorwise_ranks,
        "minimum_nonzero_factorwise_rank": min(factorwise_ranks),
        "rank_one_absent": 1 not in factorwise_ranks,
    }


