def line_action(diag: list[int], legs: list[list[int]]) -> int | None:
    """Scalar by which a diagonal gauge element acts on an invariant line
    whose basis monomials have the given e-leg index sets.  None if the
    action is not the same scalar on every monomial (line not preserved
    scalar-wise)."""
    vals = set()
    for mono in legs:
        v = 1
        for i in mono:
            v *= diag[i]
        vals.add(v)
    if len(vals) != 1:
        return None
    return vals.pop()


