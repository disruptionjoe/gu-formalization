def lam_sig(p: int, q: int, k: int) -> tuple[int, int]:
    """Signature of the induced metric form on Lambda^k of R^(p,q)."""
    n_plus = 0
    n_minus = 0
    for j in range(0, k + 1):          # j = number of negative indices chosen
        if j > q or (k - j) > p:
            continue
        cnt = comb(p, k - j) * comb(q, j)
        if j % 2 == 0:
            n_plus += cnt
        else:
            n_minus += cnt
    return (n_plus, n_minus)


def tensor_sig(s1: tuple[int, int], s2: tuple[int, int]) -> tuple[int, int]:
    (p1, q1), (p2, q2) = s1, s2
    return (p1 * p2 + q1 * q2, p1 * q2 + q1 * p2)


