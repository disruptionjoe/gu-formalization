    check("M:evenness:mu(-a)=mu(a)",
          cross(tuple(-x for x in a1), tuple(-x for x in a2)) == c, "")
    check("M:orthogonality:c.a1=c.a2=0",
          dot(c, a1) == 0 and dot(c, a2) == 0, "")
