def group_classes(p: int, q: int) -> frozenset[tuple[int, int]]:
    """Subgroup of Z/2 x Z/2 realized by pi_0(O(p,q)) sign-pair classes."""
    gens = []
    if p >= 1:
        gens.append((-1, 1))   # reflect one positive direction
    if q >= 1:
        gens.append((1, -1))   # reflect one negative direction
    classes = {(1, 1)}
    frontier = [(1, 1)]
    while frontier:
        a = frontier.pop()
        for g in gens:
            b = (a[0] * g[0], a[1] * g[1])
            if b not in classes:
                classes.add(b)
                frontier.append(b)
    return frozenset(classes)


def quadric_components(p: int, q: int, c_sign: int) -> int:
    """Number of connected components of {Q = c} on R^(p,q), sign(c) = c_sign.

    {Q = c > 0} = O(p,q)/O(p-1,q); components = |pi_0(G)| / |im pi_0(H)|.
    Empty level set -> 0.
    """
    if c_sign > 0:
        if p == 0:
            return 0
        G = group_classes(p, q)
        H = group_classes(p - 1, q)
    else:
        if q == 0:
            return 0
        G = group_classes(p, q)
        H = group_classes(p, q - 1)
    return len(G) // len(H)


