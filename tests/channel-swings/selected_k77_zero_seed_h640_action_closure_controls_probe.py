def build_packet(prime: int, full_controls: bool) -> dict:
    field = GF(prime)
    imaginary = field(-1).sqrt()
    n, nv, spin, total = 7, 14, 128, 1920
    one_dim = nv * spin
    i2 = identity_matrix(field, 2, sparse=True)
    s1 = matrix(field, [[0, 1], [1, 0]], sparse=True)
    s3 = matrix(field, [[1, 0], [0, -1]], sparse=True)
    eps = matrix(field, [[0, 1], [-1, 0]], sparse=True)
    i128 = identity_matrix(field, spin, sparse=True)
    z128 = zero_matrix(field, spin, spin, sparse=True)
    i1792 = identity_matrix(field, one_dim, sparse=True)
    i1920 = identity_matrix(field, total, sparse=True)

    def tensor_all(factors):
        out = matrix(field, [[1]], sparse=True)
        for factor in factors:
            out = out.tensor_product(factor)
        return out

    plus, minus = [], []
    for index in range(n):
        plus.append(tensor_all([s3] * index + [s1] + [i2] * (n - 1 - index)))
        minus.append(tensor_all([s3] * index + [eps] + [i2] * (n - 1 - index)))
    gammas = plus + minus
    eta = [1] * 7 + [-1] * 7

    def block_spin(value):
        return block_matrix(
            field,
            nv,
            nv,
            [[value if row == column else z128 for column in range(nv)] for row in range(nv)],
            sparse=True,
        )

    def wedge(index):
        return block_matrix(
            field,
            nv,
            nv,
            [[field(eta[row]) * gammas[row] * gammas[index] * gammas[column]
              if row != index and column not in (row, index) else z128
              for column in range(nv)] for row in range(nv)],
            sparse=True,
        )

    def k_map(index):
        return block_matrix(
            field, nv, 1,
            [[i128 if row == index else z128] for row in range(nv)],
            sparse=True,
        )

    def codiff(index):
        return block_matrix(
            field, 1, nv,
            [[field(eta[column]) * i128 if column == index else z128 for column in range(nv)]],
            sparse=True,
        )

    def symbol(index):
        # The v0.181 conditional action horn uses weights 1 and 2.  The
        # southeast coefficients are the exact formal-adjoint completion.
        weights = (i128 + gammas_product) / field(2) + field(2) * (i128 - gammas_product) / field(2)
        southeast = field(11) / field(24) * (i128 + gammas_product) / field(2) + field(11) / field(12) * (i128 - gammas_product) / field(2)
        return block_matrix(
            field, 2, 2,
            [[wedge(index) * block_spin(weights), k_map(index)],
             [-codiff(index), gammas[index] * southeast]],
            sparse=True,
        )

    gammas_product = i128
    for gamma in gammas:
        gammas_product *= gamma

    time = symbol(0)
    evolutions = [time.solve_right(symbol(index)) for index in (7, 8, 9)]

    gamma_trace = block_matrix(field, 1, nv, gammas, sparse=True)
    rs = i1792 - gamma_trace.transpose() * gamma_trace / field(14)

    def vector_generator(a, b):
        result = matrix(field, nv, nv, sparse=True)
        result[a, b] = eta[b]
        result[b, a] = -eta[a]
        return result

    def spin_generator(a, b):
        return (gammas[a] * gammas[b] - gammas[b] * gammas[a]) / field(4)

    def total_generator(a, b):
        return (
            vector_generator(a, b).tensor_product(i128)
            + identity_matrix(field, nv, sparse=True).tensor_product(spin_generator(a, b))
        )

    rotations = [total_generator(8, 9), total_generator(9, 7), total_generator(7, 8)]
    boosts = [total_generator(0, 7), total_generator(0, 8), total_generator(0, 9)]
    self_dual = [(rotations[k] + imaginary * boosts[k]) / field(2) for k in range(3)]
    anti_self_dual = [(rotations[k] - imaginary * boosts[k]) / field(2) for k in range(3)]
    z1792 = zero_matrix(field, one_dim, one_dim, sparse=True)
    c_plus = field(4) * sum((x * x for x in self_dual), z1792)
    c_minus = field(4) * sum((x * x for x in anti_self_dual), z1792)

    projectors = {
        "W192": rs * (c_plus * (c_plus + field(3) * i1792) / field(40)),
        "mirror192": rs * (c_minus * (c_minus + field(3) * i1792) / field(40)),
        "old_one_form640": rs * ((c_plus + field(3) * i1792) * (c_plus + field(8) * i1792) / field(24)),
        "one_form832": rs * (-c_plus * (c_plus + field(8) * i1792) / field(15)),
    }
    def basis_from_projector(projector):
        return projector.matrix_from_columns(list(projector.pivots()))

    zero_seed = block_matrix(
        field, 2, 1,
        [[zero_matrix(field, one_dim, spin, sparse=True)], [i128]],
        sparse=True,
    )

    def extend(one_basis, include_zero=True):
        right = i128 if include_zero else zero_matrix(field, spin, 0, sparse=True)
        return block_matrix(
            field, 2, 2,
            [[one_basis, zero_matrix(field, one_dim, right.ncols(), sparse=True)],
             [zero_matrix(field, spin, one_basis.ncols(), sparse=True), right]],
            sparse=True,
        )

    natural_bases = {name: basis_from_projector(value) for name, value in projectors.items()}
    pair_basis = basis_from_projector(projectors["W192"] + projectors["mirror192"])
    seeds = {
        "zero_form128": zero_seed,
        "W192_plus_zero": extend(natural_bases["W192"]),
        "mirror192_plus_zero": extend(natural_bases["mirror192"]),
        "W_plus_mirror_plus_zero": extend(pair_basis),
    }
    if full_controls:
        seeds["old_one_form640_plus_zero"] = extend(natural_bases["old_one_form640"])
        seeds["one_form832_plus_zero"] = extend(natural_bases["one_form832"])

    random_seed_ranks = {}
    for seed in (20260810, 20260811, 20260812):
        rng = random.Random(seed)
        entries = {}
        for column in range(192):
            for row in rng.sample(range(one_dim), 8):
                entries[(row, column)] = field(rng.randrange(1, 1000))
        random_basis = rs * matrix(field, one_dim, 192, entries, sparse=True)
        random_seed_ranks[str(seed)] = random_basis.rank()
        seeds[f"random_ker192_seed{seed}_plus_zero"] = extend(random_basis)

    e0, e1, e2 = evolutions
    words = [i1920, e0, e1, e2, e0 * e1, e0 * e2, e1 * e2, e0 * e1 * e2]

    clifford = {
        "squares_identity": all((value * value - i1920).is_zero() for value in evolutions),
        "pairwise_anticommuting": all(
            (evolutions[a] * evolutions[b] + evolutions[b] * evolutions[a]).is_zero()
            for a in range(3) for b in range(a + 1, 3)
        ),
        "word_span_rank": block_matrix(field, 1, len(words), [[value.column(0) for value in words]], sparse=True).rank(),
    }

    hulls = {}
    hull_bases = {}
    for name, seed_basis in seeds.items():
        print(f"  GF({prime}) closure {name} seed={seed_basis.ncols()}", flush=True)
        images = [word * seed_basis for word in words]
        span = block_matrix(field, 1, len(images), [images], sparse=True)
        pivots = list(span.pivots())
        basis = span.matrix_from_columns(pivots)
        hull_bases[name] = basis
        hulls[name] = {
            "seed_rank": seed_basis.rank(),
            "total_rank": len(pivots),
            "one_form_projection_rank": basis.matrix_from_rows(range(one_dim)).rank(),
            "zero_form_projection_rank": basis.matrix_from_rows(range(one_dim, total)).rank(),
            "generator_invariant": all(
                block_matrix(field, 1, 2, [[basis, value * basis]], sparse=True).rank() == len(pivots)
                for value in evolutions
            ),
        }

    zero_basis = hull_bases["zero_form128"]
    equality_to_zero = {}
    intersection_with_zero = {}
    for name, basis in hull_bases.items():
        joined_rank = block_matrix(field, 1, 2, [[zero_basis, basis]], sparse=True).rank()
        equality_to_zero[name] = joined_rank == zero_basis.ncols() == basis.ncols()
        intersection_with_zero[name] = zero_basis.ncols() + basis.ncols() - joined_rank

    natural_1280_relation = None
    if full_controls:
        old_basis = hull_bases["old_one_form640_plus_zero"]
        sector832_basis = hull_bases["one_form832_plus_zero"]
        joined_rank = block_matrix(field, 1, 2, [[old_basis, sector832_basis]], sparse=True).rank()
        natural_1280_relation = {
            "joined_rank": joined_rank,
            "intersection_rank": old_basis.ncols() + sector832_basis.ncols() - joined_rank,
            "equal": joined_rank == old_basis.ncols() == sector832_basis.ncols(),
        }

    return {
        "prime": prime,
        "time_rank": time.rank(),
        "clifford": clifford,
        "natural_projector_ranks": {name: basis.ncols() for name, basis in natural_bases.items()},
        "random_seed_ranks": random_seed_ranks,
        "hulls": hulls,
        "equal_to_zero_hull": equality_to_zero,
        "intersection_with_zero_hull": intersection_with_zero,
        "old640_and_832_h1280_relation": natural_1280_relation,
    }


def build_char0_zero_packet() -> dict:
    """Independently certify the load-bearing zero-seed rank over QQ."""
    field = QQ
    n, nv, spin, total = 7, 14, 128, 1920
    one_dim = nv * spin
    i2 = identity_matrix(field, 2, sparse=True)
    s1 = matrix(field, [[0, 1], [1, 0]], sparse=True)
    s3 = matrix(field, [[1, 0], [0, -1]], sparse=True)
    eps = matrix(field, [[0, 1], [-1, 0]], sparse=True)
    i128 = identity_matrix(field, spin, sparse=True)
    z128 = zero_matrix(field, spin, spin, sparse=True)
    i1920 = identity_matrix(field, total, sparse=True)

    def tensor_all(factors):
        out = matrix(field, [[1]], sparse=True)
        for factor in factors:
            out = out.tensor_product(factor)
        return out

    plus, minus = [], []
    for index in range(n):
        plus.append(tensor_all([s3] * index + [s1] + [i2] * (n - 1 - index)))
        minus.append(tensor_all([s3] * index + [eps] + [i2] * (n - 1 - index)))
    gammas = plus + minus
    eta = [1] * 7 + [-1] * 7
    omega = i128
    for gamma in gammas:
        omega *= gamma
    p_plus = (i128 + omega) / field(2)
    p_minus = (i128 - omega) / field(2)

    def block_spin(value):
        return block_matrix(
            field, nv, nv,
            [[value if row == column else z128 for column in range(nv)] for row in range(nv)],
            sparse=True,
        )

    def wedge(index):
        return block_matrix(
            field, nv, nv,
            [[field(eta[row]) * gammas[row] * gammas[index] * gammas[column]
              if row != index and column not in (row, index) else z128
              for column in range(nv)] for row in range(nv)],
            sparse=True,
        )

    def k_map(index):
        return block_matrix(
            field, nv, 1,
            [[i128 if row == index else z128] for row in range(nv)],
            sparse=True,
        )

    def codiff(index):
        return block_matrix(
            field, 1, nv,
            [[field(eta[column]) * i128 if column == index else z128 for column in range(nv)]],
            sparse=True,
        )

    def symbol(index):
        weights = p_plus + field(2) * p_minus
        southeast = field(11) / field(24) * p_plus + field(11) / field(12) * p_minus
        return block_matrix(
            field, 2, 2,
            [[wedge(index) * block_spin(weights), k_map(index)],
             [-codiff(index), gammas[index] * southeast]],
            sparse=True,
        )

    time = symbol(0)
    evolutions = [time.solve_right(symbol(index)) for index in (7, 8, 9)]
    e0, e1, e2 = evolutions
    words = [i1920, e0, e1, e2, e0 * e1, e0 * e2, e1 * e2, e0 * e1 * e2]
    zero_seed = block_matrix(
        field, 2, 1,
        [[zero_matrix(field, one_dim, spin, sparse=True)], [i128]],
        sparse=True,
    )
    span = block_matrix(field, 1, len(words), [[word * zero_seed for word in words]], sparse=True)
    pivots = list(span.pivots())
    basis = span.matrix_from_columns(pivots)
    return {
        "field": "QQ",
        "total_rank": len(pivots),
        "one_form_projection_rank": basis.matrix_from_rows(range(one_dim)).rank(),
        "zero_form_projection_rank": basis.matrix_from_rows(range(one_dim, total)).rank(),
        "generator_invariant": all(
            block_matrix(field, 1, 2, [[basis, value * basis]], sparse=True).rank() == len(pivots)
            for value in evolutions
        ),
    }


