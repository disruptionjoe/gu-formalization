def max_abs(matrix: np.ndarray) -> float:
    return float(np.max(np.abs(matrix))) if matrix.size else 0.0


def signature(matrix: np.ndarray) -> tuple[int, int, int]:
    hermitian = 0.5 * (matrix + matrix.conj().T)
    values = np.linalg.eigvalsh(hermitian)
    scale = max(1.0, float(np.max(np.abs(values))))
    threshold = TOL * scale
    return (
        int(np.sum(values > threshold)),
        int(np.sum(values < -threshold)),
        int(np.sum(np.abs(values) <= threshold)),
    )


def g_adjoint(matrix: np.ndarray, metric: np.ndarray) -> np.ndarray:
    return np.linalg.solve(metric, matrix.T @ metric)


def real_eigendecomposition(matrix: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    values, vectors = np.linalg.eig(matrix)
    if max_abs(values.imag) > TOL or max_abs(vectors.imag) > 2.0e-6:
        raise ValueError("fixture left the real diagonalizable branch")
    return values.real, vectors.real


def spectral_sign_and_projector(
    matrix: np.ndarray,
    gap_tolerance: float = 1.0e-7,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    values, vectors = real_eigendecomposition(matrix)
    if float(np.min(np.abs(values))) <= gap_tolerance:
        raise GapClosedError("zero lies in the spectral gap")
    inverse = np.linalg.inv(vectors)
    sign_matrix = (
        vectors @ np.diag(np.sign(values)) @ inverse
    )
    projector = 0.5 * (np.eye(matrix.shape[0]) - sign_matrix)
    return sign_matrix, projector, values


def primary_inverse_square_root(matrix: np.ndarray) -> np.ndarray:
    values, vectors = real_eigendecomposition(matrix)
    if float(np.min(values)) <= 1.0e-7:
        raise SingularPolarError("-Q^2 lost its positive real spectrum")
    inverse = np.linalg.inv(vectors)
    return vectors @ np.diag(values ** -0.5) @ inverse


def metric_inertia_even(metric: np.ndarray) -> bool:
    positive, negative, zero = signature(metric)
    return zero == 0 and positive % 2 == 0 and negative % 2 == 0


def polar_complex(
    q_field: np.ndarray,
    metric: np.ndarray,
) -> np.ndarray:
    if not metric_inertia_even(metric):
        raise SignatureParityError(
            "orthogonal real J requires even positive and negative inertia"
        )
    if abs(float(np.linalg.det(q_field))) <= 1.0e-10:
        raise SingularPolarError("Q is singular")
    inverse_root = primary_inverse_square_root(-q_field @ q_field)
    return q_field @ inverse_root


def projector_range_basis(projector: np.ndarray) -> np.ndarray:
    _left, singular_values, right_t = np.linalg.svd(projector)
    rank = int(np.sum(singular_values > TOL))
    raw_basis = right_t[:rank].T
    image = projector @ raw_basis
    basis, _upper = np.linalg.qr(image)
    return basis[:, :rank]


def divided_difference(
    values: np.ndarray,
    scalar_function,
    scalar_derivative,
) -> np.ndarray:
    out = np.zeros((len(values), len(values)))
    for left in range(len(values)):
        for right in range(len(values)):
            if abs(float(values[left] - values[right])) < 1.0e-10:
                out[left, right] = scalar_derivative(values[left])
            else:
                out[left, right] = (
                    scalar_function(values[left])
                    - scalar_function(values[right])
                ) / (values[left] - values[right])
    return out


def quotient_hessian_class(
    hessian: np.ndarray,
    gauge_basis: np.ndarray,
) -> tuple[str, np.ndarray, float]:
    gauge_null_defect = max_abs(hessian @ gauge_basis)
    full_basis, _upper = np.linalg.qr(
        np.column_stack([gauge_basis, np.eye(hessian.shape[0])])
    )
    physical_basis = full_basis[:, gauge_basis.shape[1] :]
    physical_hessian = physical_basis.T @ hessian @ physical_basis
    values = np.linalg.eigvalsh(
        0.5 * (physical_hessian + physical_hessian.T)
    )
    if np.min(values) < -TOL:
        verdict = "UNSTABLE"
    elif np.any(np.abs(values) <= TOL):
        verdict = "MODULUS"
    else:
        verdict = "STRICTLY_POSITIVE"
    return verdict, values, gauge_null_defect


def controlled_action(
    point: np.ndarray,
    hessian: np.ndarray,
    modulus_direction: np.ndarray,
    quartic_coefficient: float,
) -> float:
    modulus_coordinate = float(modulus_direction @ point)
    return float(
        0.5 * point @ hessian @ point
        + 0.25 * quartic_coefficient * modulus_coordinate**4
    )


