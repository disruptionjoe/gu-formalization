def central_coefficient(generator: np.ndarray, complex_structure: np.ndarray) -> float:
    dimension = generator.shape[0]
    return -float(np.trace(complex_structure @ generator)) / dimension


def remove_central_u1(
    generator: np.ndarray,
    complex_structure: np.ndarray,
) -> np.ndarray:
    return (
        generator
        - central_coefficient(generator, complex_structure) * complex_structure
    )


