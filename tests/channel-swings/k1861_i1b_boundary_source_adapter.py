#!/usr/bin/env python3
"""Exact horizontal metric-row controls; no full native distortion map asserted."""
from fractions import Fraction as F
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[2]


def zero():
    return [[F(0) for _ in range(4)] for _ in range(4)]


def dot(a, b, e):
    return sum(e[i]*a[i]*b[i] for i in range(4))


def trace(t, e):
    return sum(e[i]*t[i][i] for i in range(4))


def symbol(t, k, e, d):
    q, tau = dot(k, k, e), trace(t, e)
    u = [sum(e[a]*k[a]*t[a][b] for a in range(4)) for b in range(4)]
    s = dot(k, u, e)
    return [[F(d['symbol_scale'])*(-q*t[a][b]-k[a]*k[b]*tau+k[a]*u[b]+k[b]*u[a]
             +(e[a] if a == b else 0)*(q*tau-s)) for b in range(4)] for a in range(4)]


def rank(matrix):
    rows = [list(map(F, row)) for row in matrix]
    r = 0
    for c in range(len(rows[0])):
        p = next((i for i in range(r, len(rows)) if rows[i][c]), None)
        if p is None:
            continue
        rows[r], rows[p] = rows[p], rows[r]
        divisor = rows[r][c]
        rows[r] = [v/divisor for v in rows[r]]
        for i in range(len(rows)):
            if i != r:
                multiplier = rows[i][c]
                rows[i] = [v-multiplier*w for v, w in zip(rows[i], rows[r])]
        r += 1
        if r == len(rows):
            break
    return r


def verify(d):
    assert d['dimension'] == 4 and F(d['symbol_scale']) == 1
    assert F(d['trace_reversal_coefficient']) == F(1, 2)
    count = 0
    slots = [(a, b) for a in range(4) for b in range(a, 4)]
    for e, modes in [([1]*4, [(1, 0, 0, 0), (1, 2, 3, 4)]),
                     ([-1, 1, 1, 1], [(1, 0, 0, 0), (0, 2, 0, 0), (1, 0, 0, 1)])]:
        for k in modes:
            columns = []
            for a, b in slots:
                t = zero()
                t[a][b] = t[b][a] = F(1)
                out = symbol(t, k, e, d)
                assert all(sum(e[a]*k[a]*out[a][b] for a in range(4)) == 0 for b in range(4))
                columns.append([out[a][b] for a, b in slots])
                count += 1
            obtained_rank = rank(list(map(list, zip(*columns))))
            assert obtained_rank == (d['nonnull_rank'] if dot(k, k, e) else d['null_rank'])
            for z in [(1, 2, 3, 4), (F(1, 3), -2, 0, 1)]:
                gauge = [[k[a]*z[b]+k[b]*z[a] for b in range(4)] for a in range(4)]
                assert symbol(gauge, k, e, d) == zero()
                count += 1
            if dot(k, k, e):
                # Sources generated by the operator are conserved; inversion
                # must recover their image, not an arbitrary gauge representative.
                for seed in range(1, 5):
                    t = [[F((a+1)*(b+1)+seed*(a+b), seed+2) for b in range(4)] for a in range(4)]
                    J = symbol(t, k, e, d)
                    tj = trace(J, e)
                    response = [[(J[a][b]-F(d['trace_reversal_coefficient'])*(e[a] if a == b else 0)*tj)
                                 /dot(k, k, e) for b in range(4)] for a in range(4)]
                    assert symbol(response, k, e, d) == [[-v for v in row] for row in J]
                    count += 1
    # Null range and a right inverse, with k·l=1 and l·l=0.
    e, k, l = [-1, 1, 1, 1], [1, 0, 0, 1], [F(-1, 2), 0, 0, F(1, 2)]
    assert dot(k, l, e) == 1 and dot(l, l, e) == 0
    range_columns = []
    for w in [[int(i == j) for i in range(4)] for j in range(4)]+[[F(2, 3), -1, 3, F(4, 7)]]:
        kw, lw = dot(k, w, e), dot(l, w, e)
        target = [[k[a]*w[b]+k[b]*w[a]-(e[a] if a == b else 0)*kw for b in range(4)] for a in range(4)]
        t = [[l[a]*w[b]+l[b]*w[a]-kw*l[a]*l[b]
              -F(d['null_inverse_metric_coefficient'])*lw*(e[a] if a == b else 0)
              for b in range(4)] for a in range(4)]
        assert symbol(t, k, e, d) == target
        assert target[1][1]-target[2][2] == 0 and target[1][2] == 0
        range_columns.append([target[a][b] for a, b in slots])
        count += 1
    assert rank(list(map(list, zip(*range_columns)))) == 4
    J = zero()
    J[1][1], J[2][2] = 1, -1
    assert all(sum(e[a]*k[a]*J[a][b] for a in range(4)) == 0 for b in range(4))
    assert J[1][1]-J[2][2] == 2
    count += 1
    # Exact coordinate Hessian and divergence of the polynomial box response.
    a = F(d['box_quadratic_coefficient'])
    for e in [[1]*4, [-1, 1, 1, 1]]:
        laplacian_f = sum(e[i]*2*a*e[i] for i in range(4))
        actual = [[2*(2*a*e[i]-e[i]*laplacian_f) if i == j else F(0)
                   for j in range(4)] for i in range(4)]
        assert actual == [[-F(1, 2)*e[i] if i == j else 0 for j in range(4)] for i in range(4)]
        current_linear_coefficient = F(d['green_current_factor'])*(1-4)*2*a
        assert current_linear_coefficient == -1
        assert 4*current_linear_coefficient == F(d['scale_flux_per_volume']) == -4
        count += 3
    # Euclidean trace reversal is orthogonal, fixing the Sobolev constant.
    for seed in range(1, 5):
        j = [[F(a+b+seed, seed+1) for b in range(4)] for a in range(4)]
        tj = trace(j, [1]*4)
        barred = [[j[a][b]-(F(1, 2)*tj if a == b else 0) for b in range(4)] for a in range(4)]
        assert sum(v*v for row in j for v in row) == sum(v*v for row in barred for v in row)
        count += 1
    assert d['euclidean_sobolev_constant'] == 2
    assert not d['full_native_dual_injection_constructed'] and not d['companion_row_solved']
    assert not d['lorentzian_global_inverse_claimed'] and d['scope'] == 'horizontal_equation_dual_control'
    for item in d['dependencies']:
        assert hashlib.sha256((ROOT/item['path']).read_bytes()).hexdigest() == item['sha256']
    return count


if __name__ == '__main__':
    data = json.loads((ROOT/'lab/process/k1861-i1b-boundary-source-adapter.json').read_text())
    print('K1861 exact controls PASS:', verify(data), 'groups; native dual injection and companion row remain open')
